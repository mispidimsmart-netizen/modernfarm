/** টেস্ট প্ল্যান → Markdown (প্যাকেজ ZIP এ যায়) */
export function testPlanToMarkdown(): string {
  const sev: Record<TestSeverity, string> = { blocker: 'BLOCKER', major: 'MAJOR', advisory: 'ADVISORY' };
  const out: string[] = [
    '# FarmEye Controller v8 — Protection Test Plan',
    '## আর্থিং / ফিউজ / MOV / কনফরমাল কোটিং',
    '',
    '## নিরাপত্তা নিয়ম (আগে পড়ুন)',
    ...TEST_PLAN_SAFETY_RULES.map((r) => `- ${r}`),
    '',
  ];
  for (const section of PROTECTION_TEST_PLAN) {
    out.push(`## ${section.title}`, '', section.intro, '', `যন্ত্রপাতি: ${section.tools.join(', ')}`, '');
    section.steps.forEach((s, idx) => {
      out.push(`### ${idx + 1}. ${s.title} (${sev[s.severity]}${s.danger ? ', AC LIVE' : ''})`);
      out.push(`- [ ] কীভাবে: ${s.how}`);
      out.push(`- পাস শর্ত: ${s.pass}`, '');
    });
  }
  out.push('---', '', 'স্বাক্ষর: ________________   তারিখ: __________   বোর্ড সিরিয়াল: __________');
  return out.join('\n');
}
